const { chromium } = require("../../design/chat-workspace-2026-10-27/.qa/node_modules/playwright");
const fs = require("node:fs");
const path = require("node:path");
let browser;
(async () => {
  browser = await chromium.launch({ channel: "msedge", headless: true });
  const page = await browser.newPage({ viewport: { width: 1440, height: 960 } });
  const errors = []; page.on("pageerror", error => errors.push(error.message));
  const state = value => page.locator(`.ll-status-card[data-linkage-status="${value}"]`).waitFor({ timeout: 15000 });
  await page.goto("http://127.0.0.1:1436/quick-connect-preview.html?view=linkage&scenario=setup"); await state("setup");
  await page.locator(".sc-selected-project").click();
  await page.locator(".sc-project-list button").filter({ hasText: "/home/ubuntu/projects/orders" }).click();
  await page.getByRole("button", { name: "一键接入", exact: true }).click(); await state("applying"); await state("waiting");
  const address = await page.locator(".ll-address-row code").innerText();
  await page.getByRole("button", { name: "模拟客户端调用", exact: true }).click(); await state("verified");
  await page.getByRole("button", { name: "更改范围", exact: true }).click();
  await page.getByRole("group", { name: "接入生效范围" }).getByRole("button", { name: "所有项目都可用" }).click(); await state("changed");
  await page.getByRole("button", { name: "应用范围更改", exact: true }).click(); await state("applying"); await state("waiting");
  if (!await page.locator(".sc-scope-summary").innerText().then(text => text.includes("所有项目可用"))) throw new Error("scope migration failed");
  if (await page.locator(".ll-address-row code").innerText() !== address) throw new Error("scope migration changed fixed address");
  await page.locator(".sc-advanced>summary").click();
  await page.getByRole("button", { name: "重生成", exact: true }).click(); await page.getByRole("button", { name: "确定", exact: true }).click(); await state("changed");
  await page.locator(".stable-inline-actions").getByRole("button", { name: "检查并更新原接入", exact: true }).click();
  await page.getByRole("button", { name: "应用接入配置", exact: true }).click(); await state("applying"); await state("waiting");
  if (await page.locator(".ll-address-row code").innerText() !== address) throw new Error("Token update changed endpoint");
  if (errors.length) throw new Error(errors.join("\n"));
  const report = { passed: true, checks: ["从最近项目选择到一键配置", "配置完成后等待客户端验证", "项目级迁移到全局且固定地址保留", "令牌变更后更新原接入"], errors };
  fs.writeFileSync(path.resolve(__dirname, "../../.impeccable/review/connection-linkage/flow-report.json"), JSON.stringify(report, null, 2));
  console.log(JSON.stringify(report, null, 2)); await browser.close();
})().catch(async error => { console.error(error); await browser?.close(); process.exitCode = 1; });
